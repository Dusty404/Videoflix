from django.utils.encoding import force_bytes
from django.utils.http import urlsafe_base64_encode
from django.core import signing
from django.core.mail import send_mail
from django.contrib.auth.tokens import default_token_generator
from django.template.loader import render_to_string
from django.conf import settings
from django.core.mail import EmailMessage
from urllib.parse import urlencode
from pathlib import Path
from email.message import MIMEPart


registration_signer = signing.TimestampSigner(salt="email-activation")
password_reset_signer = signing.TimestampSigner(salt="password_reset")

def send_confirmation_email(user):
    """
    Build a signed activation link and send it to the user synchronously.

    Args:
        user (User): Saved account with a primary key and email address.
    """
    token = registration_signer.sign(str(user.pk))
    uidb64 = urlsafe_base64_encode(force_bytes(user.pk))
    query_params = urlencode({"uid": uidb64, "token": token})
    activation_url = (f"http://127.0.0.1:5500/pages/auth/activate.html?{query_params}")
    username = user.email.split("@")[0]
    html_message = render_to_string("emails/confirm_email.html", {"username": username, "activation_url": activation_url, "logo_url": "cid:videoflix-logo"})
    email = EmailMessage(subject="Confirm your email", body=html_message, to=[user.email])
    email.content_subtype = "html"
    logo_path = Path(settings.BASE_DIR) / "assets" / "Logo.png"

    logo = MIMEPart()
    logo.set_content(
    logo_path.read_bytes(),
    maintype="image",
    subtype="png",
    disposition="inline",
    cid="<videoflix-logo>",
)

    email.attach(logo)
    email.send()

def check_activation_token(token):
    """
    Verify an activation signature and enforce its 24-hour lifetime.

    Args:
        token (str): Timestamped token generated by registration_signer.

    Returns:
        str: The user ID stored in the signed token.

    Raises:
        signing.SignatureExpired: If the token is older than 24 hours.
        signing.BadSignature: If the signature cannot be verified.
    """
    return registration_signer.unsign(token, max_age=60 * 60 * 24)


def send_password_reset_email(user):
    """
    Create a Django password reset token and email its frontend link.

    Args:
        user (User): Saved account receiving the reset email.
    """
    token = default_token_generator.make_token(user)
    uidb64 = urlsafe_base64_encode(force_bytes(user.pk))
    query_params = urlencode({"uid": uidb64, "token": token})
    reset_url = f"http://127.0.0.1:5500/pages/auth/confirm_password.html?{query_params}"
    html_message = render_to_string("emails/password_reset.html", {"reset_url": reset_url, "expiry_hours": 24, "logo_url": "cid:videoflix-logo"})
    email = EmailMessage(subject="Reset your Password", body=html_message, to=[user.email])
    email.content_subtype = "html"
    logo_path = Path(settings.BASE_DIR) / "assets" / "Logo.png"
    
    logo = MIMEPart()
    logo.set_content(
        logo_path.read_bytes(),
        maintype="image",
        subtype="png",
        disposition="inline",
        cid="<videoflix-logo>",
    )
    
    email.attach(logo)
    email.send()